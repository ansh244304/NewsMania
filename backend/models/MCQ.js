import mongoose from "mongoose";

const mcqSchema = new mongoose.Schema(
  {
    // Null for MCQs written by an admin without attaching them to an article.
    newsId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "News",
      default: null
    },

    question: {
      type: String,
      required: true,
      trim: true
    },

    options: {
      type: [String],
      required: true,
      validate: {
        validator: function (value) {
          return value.length === 4;
        },
        message: "MCQ must have exactly 4 options"
      }
    },

    correctAnswer: {
      type: String,
      required: true
    },

    explanation: {
      type: String,
      default: ""
    },

    difficulty: {
      type: String,
      enum: ["Easy", "Medium", "Hard"],
      default: "Medium"
    },

    exam: {
      type: [String],
      default: []
    },

    category: {
      type: String,
      default: "Current Affairs"
    },

    // "ai" = generated by Gemini, "manual" = written by an admin.
    source: {
      type: String,
      enum: ["ai", "manual"],
      default: "ai"
    },

    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null
    }
  },
  {
    timestamps: true
  }
);

export default mongoose.model("MCQ", mcqSchema);